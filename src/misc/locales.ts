export type TLocale = "en" | "ru";
export type TTranslationVars = Record<string, string | number>;

export const LOCALE_NAMES: Record<TLocale, string> = { en: "English", ru: "Русский" };

export const LOCALES: Record<TLocale, Record<TTranslationKey, string>> = { en, ru };

export function translate(locale: TLocale, key: TTranslationKey, vars?: TTranslationVars) {
    const text = LOCALES[locale][key] ?? LOCALES.en[key];
    if (!vars)
        return text;
    return text.replace(/\{(\w+)\}/g, (placeholder, name: string) => vars[name] !== undefined ? String(vars[name]) : placeholder);
}
